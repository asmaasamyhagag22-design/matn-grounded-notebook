"""Repository supplies raw records and statistics; Python performs all scoring."""
from typing import Protocol


class Repository(Protocol):
    def create_notebook(self, notebook: str): ...
    def source_ids(self, notebook: str) -> list[str]: ...
    def validate_selection(self, notebook: str, selected: list[str]): ...
    def selected_chunks(self, notebook: str, selected: list[str]) -> list[dict]: ...
    def source_stats(self, selected: list[str], variant: str) -> dict: ...
    def delete_source(self, source_id: str): ...
    def canonical_export(self) -> bytes: ...
    def get_embedding(self, digest: str, version: str, text: str): ...

    def source_rows(self, notebook: str) -> list[dict]: ...
    def add_source(self, notebook: str, doc_id: str, metadata: dict, chunks: list[dict]) -> str: ...
    def raw_postings(self, selected: list[str], variant: str) -> list[dict]: ...
    def vectors(self, selected: list[str], variant: str) -> dict: ...
    def put_embedding(self, digest: str, version: str, text: str, vector: list[float]) -> str: ...
    def link_embedding(self, source: str, chunk: str, variant: str, digest: str, version: str, text: str): ...
    def integrity(self) -> dict: ...
